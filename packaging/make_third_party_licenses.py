"""Write THIRD_PARTY_LICENSES with the licenses of everything shipped in Aulari.exe.

Covers the runtime packages pinned in requirements.txt, the Python runtime,
Tcl/Tk (used by tkinter) and the PyInstaller bootloader. License texts are
read from the installed distributions, so run it with the dev environment
active, from the project folder:

    python packaging/make_third_party_licenses.py
"""

import importlib.metadata
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD_PARTY_LICENSES"
REQUIREMENTS = ROOT / "requirements.txt"
SEPARATOR = "=" * 78
# License texts for packages whose wheel ships none (copied from their repositories).
LOCAL_LICENSES = ROOT / "packaging" / "licenses"
_PINNED = re.compile(r"^([A-Za-z0-9_.\-]+)==([^\s\\]+)")
# Files that are not distributions but are also bundled in the executable.
EXTRA_FILES = [
    ("Python", Path(sys.base_prefix) / "LICENSE.txt"),
    # Tcl and Tk share the same license; the Windows Python install ships Tk's copy.
    ("Tcl/Tk", Path(sys.base_prefix) / "tcl" / "tk8.6" / "license.terms"),
]


def pinned_packages(requirements: Path) -> list[tuple[str, str]]:
    """Return (name, version) for every 'name==version' line of a requirements file.

    Raises: OSError if the file cannot be read.
    """
    result = []
    for line in requirements.read_text(encoding="utf-8").splitlines():
        match = _PINNED.match(line.strip())
        if match is not None:
            result.append((match.group(1), match.group(2)))
    return result


def license_texts(distribution: importlib.metadata.Distribution) -> list[str]:
    """Return the license file texts of an installed distribution (may be empty)."""
    texts = []
    for name in distribution.metadata.get_all("License-File") or []:
        content = distribution.read_text(f"licenses/{name}") or distribution.read_text(name)
        if content:
            texts.append(content.strip())
    return texts


def package_section(name: str, version: str) -> str:
    """Return the section of one package: header, declared license and texts.

    Raises: importlib.metadata.PackageNotFoundError if it is not installed.
    """
    distribution = importlib.metadata.distribution(name)
    metadata = distribution.metadata
    declared = metadata.get("License-Expression") or metadata.get("License") or ""
    homepage = metadata.get("Home-page") or ""
    texts = license_texts(distribution)
    local = LOCAL_LICENSES / f"{name}.txt"
    if not texts and local.is_file():
        texts = [local.read_text(encoding="utf-8").strip()]
    if not texts:
        texts = [f"License: {declared.strip() or 'see the project page'} ({homepage})"]
    summary = declared.strip().splitlines()[0] if declared.strip() else "see the text below"
    header = f"{name} {version}\nLicense: {summary}"
    result = "\n".join([SEPARATOR, header, SEPARATOR, "", "\n\n".join(texts), ""])
    return result


def file_section(title: str, path: Path) -> str:
    """Return the section of a bundled component whose license is a plain file.

    Raises: OSError if the file cannot be read.
    """
    content = path.read_text(encoding="utf-8", errors="replace").strip()
    result = "\n".join([SEPARATOR, title, SEPARATOR, "", content, ""])
    return result


def main() -> None:
    """Build the whole file from the requirements and the extra components."""
    sections = [
        "Third-party software included in Aulari\n"
        "Generated by packaging/make_third_party_licenses.py\n"
    ]
    for name, version in pinned_packages(REQUIREMENTS):
        sections.append(package_section(name, version))
    for title, path in EXTRA_FILES:
        sections.append(file_section(title, path))
    sections.append(package_section("pyinstaller", importlib.metadata.version("pyinstaller")))
    OUTPUT.write_text("\n".join(sections), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT} ({len(sections) - 1} components)")


if __name__ == "__main__":
    main()
