"""Export Moodle calendar events to an iCalendar (.ics) file (D3, design.md section 8).

Own exporter, no external library, following RFC 5545:
- UID = moodle-<eventid>@<academic year>.<host>, stable across exports (the
  year keeps events of different academic year sites apart, decision D6);
- times in UTC; events without duration have no DTEND (zero duration);
- SEQUENCE from the registry, raised when an event changes;
- text escaped, lines folded at 75 octets, CRLF line ends.
The file is replaced atomically on every export (it is generated by the app).
"""

import html
import os
import re
import secrets
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path
from urllib.parse import urlparse

from campus_sync import __version__
from campus_sync.moodle_client import MoodleClient, array_param
from campus_sync.registry import Registry

CALENDAR_FILENAME = "calendari.ics"
DAYS_BEFORE = 30
DAYS_AFTER = 365
MAX_LINE_OCTETS = 75
CRLF = "\r\n"
PRODID = f"-//CampusSync//CampusSync {__version__}//EN"
UTC_FORMAT = "%Y%m%dT%H%M%SZ"
_TAG = re.compile(r"<[^>]+>")
_SPACES = re.compile(r"\s+")


@dataclass(frozen=True)
class CalendarEvent:
    """The fields of a Moodle event that go into the .ics file."""

    event_id: int
    name: str
    description: str
    course_id: int
    timestart: int
    timeduration: int
    timemodified: int
    url: str


def calendar_path(destination: Path, academic_year: str) -> Path:
    """Return <destination>/<academic year>/calendari.ics."""
    result = destination / academic_year / CALENDAR_FILENAME
    return result


def escape_text(text: str) -> str:
    """Escape a TEXT value: backslash, semicolon, comma and line breaks (RFC 5545 3.3.11)."""
    result = text.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,")
    result = result.replace("\r\n", "\\n").replace("\n", "\\n").replace("\r", "\\n")
    return result


def fold_line(line: str) -> str:
    """Fold a content line at 75 octets without splitting UTF-8 characters (RFC 5545 3.1).

    Continuation lines start with one space, which counts towards their 75 octets.
    """
    pieces = []
    current = ""
    limit = MAX_LINE_OCTETS
    for char in line:
        if len((current + char).encode("utf-8")) > limit:
            pieces.append(current)
            current = ""
            limit = MAX_LINE_OCTETS - 1  # room for the leading space
        current = current + char
    pieces.append(current)
    result = (CRLF + " ").join(pieces)
    return result


def format_utc(timestamp: int) -> str:
    """Return a Unix timestamp as an iCalendar UTC date-time: 20261106T170500Z."""
    result = datetime.fromtimestamp(timestamp, UTC).strftime(UTC_FORMAT)
    return result


def plain_text(description: str) -> str:
    """Return a Moodle HTML description as one line of plain text."""
    without_tags = _TAG.sub(" ", description)
    result = _SPACES.sub(" ", html.unescape(without_tags)).strip()
    return result


def event_from_moodle(data: dict) -> CalendarEvent:
    """Return a CalendarEvent from one core_calendar_get_calendar_events entry."""
    result = CalendarEvent(
        event_id=int(data["id"]),
        name=str(data.get("name", "")),
        description=plain_text(str(data.get("description") or "")),
        course_id=int(data.get("courseid") or 0),
        timestart=int(data.get("timestart", 0)),
        timeduration=int(data.get("timeduration") or 0),
        timemodified=int(data.get("timemodified") or 0),
        url=str(data.get("url") or ""),
    )
    return result


def fetch_events(client: MoodleClient, course_ids: list[int], now: datetime) -> list[CalendarEvent]:
    """Return the events of the courses in the window today -30 days to +1 year.

    All course ids must be passed: without them Moodle omits course events.

    Raises: MoodleError, requests.RequestException.
    """
    params = array_param("events[courseids]", course_ids)
    params["options[userevents]"] = 1
    params["options[siteevents]"] = 1
    params["options[timestart]"] = int((now - timedelta(days=DAYS_BEFORE)).timestamp())
    params["options[timeend]"] = int((now + timedelta(days=DAYS_AFTER)).timestamp())
    data = client.call("core_calendar_get_calendar_events", params)
    result = [event_from_moodle(event) for event in data.get("events", [])]
    return result


def _event_order(event: CalendarEvent) -> tuple[int, int]:
    """Sort key for events: start time, then id (stable output)."""
    result = (event.timestart, event.event_id)
    return result


def _event_lines(
    event: CalendarEvent, uid_domain: str, alias: str, sequence: int, stamp: str
) -> list[str]:
    """Return the unfolded content lines of one VEVENT."""
    summary = f"[{alias}] {event.name}" if alias else event.name
    lines = [
        "BEGIN:VEVENT",
        f"UID:moodle-{event.event_id}@{uid_domain}",
        f"DTSTAMP:{stamp}",
        f"DTSTART:{format_utc(event.timestart)}",
    ]
    if event.timeduration > 0:
        lines.append(f"DTEND:{format_utc(event.timestart + event.timeduration)}")
    lines.append(f"SUMMARY:{escape_text(summary)}")
    if event.description:
        lines.append(f"DESCRIPTION:{escape_text(event.description)}")
    if urlparse(event.url).scheme in {"http", "https"} and not re.search(r"[\r\n]", event.url):
        lines.append(f"URL:{event.url}")
    if event.timemodified:
        lines.append(f"LAST-MODIFIED:{format_utc(event.timemodified)}")
    lines.append(f"SEQUENCE:{sequence}")
    lines.append("END:VEVENT")
    return lines


@dataclass(frozen=True)
class IcsOptions:
    """Calendar-wide settings for build_ics()."""

    uid_domain: str
    calendar_name: str
    aliases: dict[int, str]


def build_ics(
    events: list[CalendarEvent], options: IcsOptions, sequences: dict[int, int], now: datetime
) -> str:
    """Return the complete .ics text for the events.

    options.aliases maps course id -> folder alias for the '[SO]' prefix;
    sequences maps event id -> SEQUENCE.
    """
    stamp = now.astimezone(UTC).strftime(UTC_FORMAT)
    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        f"PRODID:{PRODID}",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        f"X-WR-CALNAME:{escape_text(options.calendar_name)}",
    ]
    for event in sorted(events, key=_event_order):
        alias = options.aliases.get(event.course_id, "")
        sequence = sequences.get(event.event_id, 0)
        lines.extend(_event_lines(event, options.uid_domain, alias, sequence, stamp))
    lines.append("END:VCALENDAR")
    result = "".join([fold_line(line) + CRLF for line in lines])
    return result


def write_atomic(path: Path, text: str) -> None:
    """Write text to path through a temporary file in the same folder, then replace.

    Raises: OSError on write errors (the old file is kept intact).
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(f".{path.name}.{secrets.token_hex(4)}.part")
    try:
        with temp.open("w", encoding="utf-8", newline="") as out_file:
            out_file.write(text)
        os.replace(temp, path)
    finally:
        temp.unlink(missing_ok=True)


@dataclass(frozen=True)
class CalendarRequest:
    """What to export: which site, courses and where."""

    site_id: int
    site_url: str
    academic_year: str
    destination: Path
    aliases: dict[int, str]


def export_calendar(
    client: MoodleClient, registry: Registry, request: CalendarRequest, now: datetime
) -> tuple[Path, int]:
    """Fetch the events, write the .ics file and return (path, number of events).

    Raises: MoodleError, requests.RequestException, OSError.
    """
    events = fetch_events(client, sorted(request.aliases), now)
    sequences = {
        event.event_id: registry.event_sequence(request.site_id, event.event_id, event.timemodified)
        for event in events
    }
    host = urlparse(request.site_url).hostname or "moodle"
    options = IcsOptions(
        uid_domain=f"{request.academic_year}.{host}",
        calendar_name=f"Campus {request.academic_year}",
        aliases=request.aliases,
    )
    text = build_ics(events, options, sequences, now)
    path = calendar_path(request.destination, request.academic_year)
    write_atomic(path, text)
    result = (path, len(events))
    return result
