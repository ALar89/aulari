"""Read-only window that shows Novedades.txt (RF14) with a scroll bar.

The file is generated by the app itself, but it is shown inside Aulari
instead of being opened with another program: long lists scroll here and
nothing external is launched.
"""

import tkinter as tk
from pathlib import Path
from tkinter import ttk

from aulari.texts import text

PADDING = 8
WIDTH_CHARS = 90
HEIGHT_LINES = 25


class NewsWindow(tk.Toplevel):
    """A Toplevel with a read-only Text widget and a vertical scroll bar."""

    def __init__(self, parent: tk.Misc, path: Path) -> None:
        """Create the window and load the file.

        Raises: OSError if the file cannot be read.
        """
        super().__init__(parent)
        self.title(text("news_window_title"))
        content = path.read_text(encoding="utf-8")
        frame = ttk.Frame(self, padding=PADDING)
        frame.pack(fill="both", expand=True)
        scroll = ttk.Scrollbar(frame, orient="vertical")
        self.text = tk.Text(
            frame, wrap="none", width=WIDTH_CHARS, height=HEIGHT_LINES, yscrollcommand=scroll.set
        )
        scroll.configure(command=self.text.yview)
        scroll.pack(side="right", fill="y")
        self.text.pack(side="left", fill="both", expand=True)
        self.text.insert("1.0", content)
        self.text.configure(state="disabled")
        ttk.Button(self, text=text("close_button"), command=self.destroy).pack(pady=(0, PADDING))
